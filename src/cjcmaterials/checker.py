# The rules, one function per group
# --------------------------------------------------------------------------------------------------

def _check_completeness(material: Material, file: Path) -> list[str]:
    """Every description and source has what a reader needs to find and judge the values."""
    problems = []
    if material.name != file.stem:
        problems.append(f"{file.name}: name {material.name!r} differs from the file name {file.stem!r}.")
    labels = [description.label for description in material.descriptions]
    for label in sorted({label for label in labels if labels.count(label) > 1}):
        problems.append(f"{material.name}: description label {label!r} is used more than once.")

    # Descriptions need sources and a valid range.
    for description in material.descriptions:
        where = f"{material.name}, description {description.label!r}"
        if not description.sources:
            problems.append(f"{where}: no sources (add 'sources: [<key>]').")
        if not description.valid_range_thz:
            problems.append(f"{where}: no valid_range_thz.")

    # Sources need every field, and an unused source is probably a typo in a key.
    used = {source.key for description in material.descriptions for source in _all_sources(description)}
    for source in material.sources:
        where = f"{material.name}, source {source.key!r}"
        if source.type not in SOURCE_TYPES:
            problems.append(f"{where}: type {source.type!r} is not one of {', '.join(SOURCE_TYPES)}.")
        for field_name, value in (("id", source.identifier), ("citation", source.citation),
                                  ("location", source.location)):
            if not value:
                problems.append(f"{where}: no {field_name}.")
        if not source.valid_range_thz:
            problems.append(f"{where}: no valid_range_thz.")
        if source.checked != "no" and not _CHECKED_PATTERN.match(source.checked):
            problems.append(f"{where}: checked must be 'no' or '<who>, <YYYY-MM-DD>', got {source.checked!r}.")
        if source.key not in used:
            problems.append(f"{where}: defined but not used by any description or parameter.")
    return problems


def _check_identifiers(material: Material) -> list[str]:
    """Each identifier has the syntax of its type (an ISBN also a correct check digit)."""
    problems = []
    for source in material.sources:
        if source.type in _IDENTIFIER_RULES and source.identifier:
            is_valid, expected = _IDENTIFIER_RULES[source.type]
            if not is_valid(source.identifier):
                problems.append(f"{material.name}, source {source.key!r}: {source.identifier!r} is not {expected}.")
    return problems


def _check_ranges(material: Material) -> list[str]:
    """Ranges are well formed, descriptions stay inside their sources' ranges and their tables."""
    problems = []

    # Every interval: finite, positive and increasing.
    owners = [(f"source {source.key!r}", source.valid_range_thz) for source in material.sources]
    owners += [(f"description {description.label!r}", description.valid_range_thz)
               for description in material.descriptions]
    for owner, ranges in owners:
        for low, high in ranges:
            if not (np.isfinite(low) and np.isfinite(high) and 0.0 < low < high):
                problems.append(f"{material.name}, {owner}: range [{low:g}, {high:g}] THz must have 0 < min < max.")

    # A description claims validity only where all of its sources do.
    for description in material.descriptions:
        for source in _all_sources(description):
            if source.valid_range_thz and not _covers(source.valid_range_thz, description.valid_range_thz):
                problems.append(
                    f"{material.name}, description {description.label!r}: its range "
                    f"({_format_ranges(description.valid_range_thz)} THz) extends beyond that of source "
                    f"{source.key!r} ({_format_ranges(source.valid_range_thz)} THz)."
                )

        # A table cannot be valid where it has no data (n and kappa both needed).
        file = description.parameters.get("file")
        if file is None:
            continue
        try:
            table = read_nk_table(file)
        except (OSError, ValueError) as error:
            problems.append(f"{material.name}, description {description.label!r}: table cannot be read: {error}")
            continue
        low = max(table.n_freq[0], table.kappa_freq[0]) / 1e12
        high = min(table.n_freq[-1], table.kappa_freq[-1]) / 1e12
        if not _covers([(low, high)], description.valid_range_thz):
            problems.append(
                f"{material.name}, description {description.label!r}: its range "
                f"({_format_ranges(description.valid_range_thz)} THz) extends beyond the table, which has "
                f"n and kappa only at {low:.4g}-{high:.4g} THz."
            )
    return problems


def _carrier_variants(description: Description) -> list[tuple[str | None, float | None]]:
    """(carrier_type, carrier_density) combinations at which a description is evaluated for sanity."""
    # Models without free carriers are evaluated once, as they are.
    if "carrier_density" not in inspect.signature(MODELS[description.model]).parameters:
        return [(None, None)]
    densities = _SANITY_CARRIER_DENSITIES.get(description.model, _BULK_SANITY_CARRIER_DENSITIES)
    types = [carrier_type for carrier_type, block in CARRIER_BLOCKS.items() if block in description.parameters]
    return [(carrier_type, density) for carrier_type in (types or [None]) for density in densities]


def _check_physics(material: Material) -> list[str]:
    """Parameters have physical signs, and each description gives a finite n and kappa >= 0 in its range."""
    problems = []
    for description in material.descriptions:
        where = f"{material.name}, description {description.label!r}"
        found_before = len(problems)

        # Signs of known parameters, wherever they appear.
        for path, name, value in _walk_parameters(description.parameters):
            if not isinstance(value, float):
                continue
            if name in _POSITIVE_PARAMETERS and not value > 0.0:
                problems.append(f"{where}: {path} = {value:g} must be > 0.")
            if name in _NON_NEGATIVE_PARAMETERS and not value >= 0.0:
                problems.append(f"{where}: {path} = {value:g} must be >= 0.")
            if name == "mobility" and not value > 0.0:
                problems.append(f"{where}: {path} = {value:g} must be > 0.")
        well_formed = all(np.isfinite(low) and np.isfinite(high) and 0.0 < low < high
                          for low, high in description.valid_range_thz)
        if not description.valid_range_thz or not well_formed or len(problems) > found_before:
            continue

        # Evaluate the description at every carrier variant over its own valid range.
        omega = _sanity_frequencies(description.valid_range_thz)
        for carrier_type, density in _carrier_variants(description):
            variant = "" if carrier_type is None and density is None else (
                f" (carrier_type={carrier_type!r}, carrier_density={density:g})" if density is not None
                else f" (carrier_type={carrier_type!r})")
            try:
                inputs = _model_inputs(material, description, density, carrier_type)
                with warnings.catch_warnings():
                    warnings.simplefilter("ignore")
                    index = refractive_index(material, omega, carrier_density=density,
                                             carrier_type=carrier_type, description=description.label)
            except (ValueError, OSError) as error:
                problems.append(f"{where}{variant}: cannot be evaluated: {error}")
                continue
            if not np.all(np.isfinite(index)):
                problems.append(f"{where}{variant}: n or kappa is not finite somewhere in its valid range.")
            elif np.any(index.imag < -1e-12):
                problems.append(f"{where}{variant}: kappa < 0 (gain) at {np.count_nonzero(index.imag < -1e-12)} "
                                "frequencies in its valid range.")

            # Free-carrier quantities: plasma frequency, mobility and scattering time must be positive.
            if "effective_mass_ratio" in inputs and density:
                omega_p = plasma_omega(density, effective_mass_ratio=inputs["effective_mass_ratio"],
                                       eps_inf=inputs.get("eps_inf", 1.0))
                if not (np.isfinite(omega_p) and omega_p > 0.0):
                    problems.append(f"{where}{variant}: plasma frequency is not positive.")
            if "mobility" in inputs and not np.all(np.asarray(inputs["mobility"]) > 0.0):
                problems.append(f"{where}{variant}: mobility is not positive.")
            if "effective_mass_ratio" in inputs:
                tau = (inputs["scattering_time"] if inputs.get("scattering_time") is not None else
                       scattering_time_from_mobility(inputs.get("mobility", 0.0),
                                                     effective_mass_ratio=inputs["effective_mass_ratio"]))
                if not np.all(np.asarray(tau) > 0.0):
                    problems.append(f"{where}{variant}: scattering time is not positive.")
    return problems


