def _plain(text: str) -> str:
    """Lower case without accents or punctuation, for comparing names and titles."""
    # Letters that are not an accented base letter (o-slash, ae, ...) are spelled out as in English citations.
    text = text.lower().translate(_SPELLED_OUT)
    decomposed = unicodedata.normalize("NFKD", text)
    ascii_text = "".join(char for char in decomposed if not unicodedata.combining(char))
    return re.sub(r"[^a-z0-9]+", " ", ascii_text.lower()).strip()


def fetch_doi_metadata(doi: str, *, timeout: float = 15.0) -> dict:
    """Title, first author's surname and year of a DOI, from doi.org content negotiation.

    Asking ``https://doi.org/<doi>`` for CSL JSON both proves that the DOI
    resolves and returns the registered metadata (Crossref, DataCite, ...).

    Returns
    -------
    dict
        ``{"title": str, "first_author": str, "year": int | None}``.

    Raises
    ------
    OSError
        If the DOI does not resolve or the network fails (``urllib.error.URLError``).
    """
    # Content negotiation: the same URL a reader would click, asked for machine-readable metadata.
    request = urllib.request.Request(f"https://doi.org/{doi}",
                                     headers={"Accept": "application/vnd.citationstyles.csl+json",
                                              "User-Agent": "cjcmaterials-check-library"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        record = json.loads(response.read().decode("utf-8"))

    # The fields to compare with the citation; any may be absent in the registry.
    title = record.get("title", "")
    title = title[0] if isinstance(title, list) and title else title
    authors = record.get("author") or [{}]
    date_parts = (record.get("issued") or {}).get("date-parts") or [[None]]
    return {"title": str(title or ""), "first_author": str(authors[0].get("family", "")),
            "year": date_parts[0][0]}


def compare_citation(source: Source, metadata: dict) -> list[str]:
    """Differences between a source's citation text and its DOI metadata.

    Checks that the first author's surname and the year appear in the
    citation, and that most words of the registered title (at least 70 % of
    those with four or more letters) do: enough to catch a DOI that points at
    another paper, tolerant of abbreviations and punctuation.
    """
    problems = []
    citation = _plain(source.citation)
    where = f"source {source.key!r} (doi {source.identifier})"

    # First author and year are short and unambiguous.
    surname = _plain(metadata.get("first_author", ""))
    if surname and surname not in citation:
        problems.append(f"{where}: first author {metadata['first_author']!r} is not in the citation.")
    year = metadata.get("year")
    if year and str(year) not in citation:
        problems.append(f"{where}: year {year} is not in the citation.")

    # The title: compare its longer words, since citations abbreviate and drop punctuation.
    words = [word for word in _plain(metadata.get("title", "")).split() if len(word) >= 4]
    if words:
        found = sum(word in citation.split() for word in words) / len(words)
        if found < 0.7:
            problems.append(f"{where}: the citation does not match the registered title {metadata['title']!r}.")
    return problems


def url_responds(url: str, *, timeout: float = 15.0) -> bool:
    """Whether an http(s) URL answers with a status below 400."""
    request = urllib.request.Request(url, headers={"User-Agent": "cjcmaterials-check-library"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return response.status < 400
    except (urllib.error.URLError, OSError, ValueError):
        return False


def _check_online(materials: list[Material], timeout: float) -> list[str]:
    """DOIs resolve and match their citation; URLs respond. ISBNs have no online check."""
    problems = []
    for material in materials:
        for source in material.sources:
            if source.type == "doi" and is_valid_doi(source.identifier):
                try:
                    metadata = fetch_doi_metadata(source.identifier, timeout=timeout)
                except (urllib.error.URLError, OSError, ValueError) as error:
                    problems.append(f"{material.name}, source {source.key!r}: doi {source.identifier} "
                                    f"does not resolve ({error}).")
                    continue
                problems += [f"{material.name}, {message}" for message in compare_citation(source, metadata)]
            elif source.type == "url" and is_valid_url(source.identifier):
                if not url_responds(source.identifier, timeout=timeout):
                    problems.append(f"{material.name}, source {source.key!r}: {source.identifier} does not respond.")
    return problems


