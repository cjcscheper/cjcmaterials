# Helpers
# --------------------------------------------------------------------------------------------------

def _format_ranges(ranges: tuple[tuple[float, float], ...]) -> str:
    """``0.1-20, 350-1000`` style text (THz implied); a dash when there are none."""
    return ", ".join(f"{low:g}-{high:g}" for low, high in ranges) if ranges else "-"


def _merged(ranges: Iterable[tuple[float, float]]) -> list[tuple[float, float]]:
    """Overlapping or touching intervals joined, so coverage can be tested interval by interval."""
    merged: list[tuple[float, float]] = []
    for low, high in sorted(ranges):
        if merged and low <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], high))
        else:
            merged.append((low, high))
    return merged


def _covers(outer: Iterable[tuple[float, float]], inner: Iterable[tuple[float, float]]) -> bool:
    """Whether every interval of ``inner`` lies inside the union of ``outer``."""
    union = _merged(outer)
    return all(any(low >= a and high <= b for a, b in union) for low, high in inner)


def _all_sources(description: Description) -> list[Source]:
    """The description's own sources and those of its parameters, each once."""
    found: dict[str, Source] = {source.key: source for source in description.sources}
    for sources in description.parameter_sources.values():
        found.update({source.key: source for source in sources})
    return list(found.values())


def _walk_parameters(parameters: dict, prefix: str = "") -> Iterable[tuple[str, str, object]]:
    """(path, name, value) for every scalar parameter, also inside carrier blocks, mobility models and oscillators."""
    for name, value in parameters.items():
        path = f"{prefix}{name}"
        if isinstance(value, dict):
            yield from _walk_parameters(value, f"{path}.")
        elif isinstance(value, list):
            for index, item in enumerate(value):
                if isinstance(item, dict):
                    yield from _walk_parameters(item, f"{path}[{index}].")
        else:
            yield path, name, value


def _sanity_frequencies(ranges: tuple[tuple[float, float], ...]) -> np.ndarray:
    """40 log-spaced angular frequencies inside each valid interval [rad/s]."""
    return np.concatenate([2.0 * np.pi * 1e12 * np.geomspace(low, high, 40) for low, high in ranges])


