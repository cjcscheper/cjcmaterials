"""Checks of a material library, and the generated overview ``LIBRARY.md``.

:func:`check_library` runs every rule over a folder of material files and
returns a :class:`LibraryCheck` with the problems grouped by rule and the
sources nobody has checked yet; ``python -m cjcmaterials.check_library`` is the
command-line front end. What the rules can and cannot verify is explained in
THEORY.md: they catch missing, malformed and unphysical entries, and with
``online=True`` a DOI that points at a different paper, but they cannot tell
whether a number was copied correctly from its source. That is what the
``checked`` field of every source is for.
"""

from __future__ import annotations

import inspect
import json
import re
import unicodedata
import urllib.error
import urllib.request
import warnings
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlparse

import numpy as np

from cjcmaterials.library import LIBRARY_DIR, SOURCE_TYPES, Description, Material, Source, load_material_file
from cjcmaterials.models import MODELS, plasma_omega, scattering_time_from_mobility
from cjcmaterials.optics import CARRIER_BLOCKS, _model_inputs, refractive_index
from cjcmaterials.tables import read_nk_table

# First line of LIBRARY.md: it is generated, and says how.
OVERVIEW_HEADER = "Generated by `python -m cjcmaterials.check_library --write-overview`; do not edit."

# LIBRARY.md sits in the repository root of a source checkout (src/cjcmaterials/checker.py -> root).
_REPOSITORY_ROOT = Path(__file__).resolve().parents[2]

# The rule groups, in the order they are reported.
GROUPS = ("loading", "completeness", "identifiers", "valid ranges", "physical sanity", "overview", "online")

# Carrier densities at which the sanity check evaluates a model with free carriers. Graphene takes a
# sheet density [m^-2] and needs one > 0; the bulk models are tried without carriers (None: the
# file's value or none), and at a moderate and a high density [m^-3].
_SANITY_CARRIER_DENSITIES = {"graphene_sheet": (1e15, 1e17)}
_BULK_SANITY_CARRIER_DENSITIES = (None, 1e22, 1e25)

# Parameters that must be > 0, and those that must be >= 0, wherever they appear (also in carrier blocks).
_POSITIVE_PARAMETERS = {"eps_inf", "effective_mass_ratio", "scattering_time", "thickness", "temperature",
                        "fermi_velocity", "n_ref", "alpha", "resonance_omega", "mu_max", "n"}
_NON_NEGATIVE_PARAMETERS = {"carrier_density", "damping", "strength", "mu_min", "kappa"}

# Patterns of the identifiers and of a filled-in 'checked' field.
_DOI_PATTERN = re.compile(r"^10\.\d{4,9}/\S+$")
_CHECKED_PATTERN = re.compile(r"^\S.*,\s*\d{4}-\d{2}-\d{2}$")

# Letters without a Unicode decomposition, as they are usually written in ASCII.
_SPELLED_OUT = str.maketrans({"ø": "o", "æ": "ae", "œ": "oe", "ß": "ss", "ł": "l", "đ": "d", "ð": "d", "þ": "th"})


@dataclass(frozen=True)
class LibraryCheck:
    """Result of :func:`check_library`.

    Attributes
    ----------
    problems : dict
        Rule group (see ``GROUPS``) -> messages; only groups with problems appear.
    unchecked_sources : tuple of str
        One line per source whose ``checked`` field is still ``no``.
    materials : tuple of str
        Names of the materials that were loaded and checked.
    passed : bool
        True when there are no problems (and, with ``require_checked``, no unchecked sources).
    """

    problems: dict[str, tuple[str, ...]]
    unchecked_sources: tuple[str, ...]
    materials: tuple[str, ...]
    passed: bool


# --------------------------------------------------------------------------------------------------
# Identifier syntax
# --------------------------------------------------------------------------------------------------

def is_valid_doi(doi: str) -> bool:
    """``10.<registrant>/<suffix>``: a registrant code of 4-9 digits and a suffix without spaces."""
    return bool(_DOI_PATTERN.match(doi))


def is_valid_isbn(isbn: str) -> bool:
    """ISBN-10 or ISBN-13 (hyphens and spaces allowed) with a correct check digit.

    ISBN-10: ``sum(weight * digit)`` with weights 10..1 is divisible by 11
    (the last digit may be X = 10). ISBN-13: digits weighted 1, 3, 1, 3, ...
    sum to a multiple of 10.
    """
    digits = isbn.replace("-", "").replace(" ", "").upper()

    # ISBN-10: nine digits and a check character that may be X.
    if len(digits) == 10 and digits[:9].isdigit() and (digits[9].isdigit() or digits[9] == "X"):
        values = [int(char) for char in digits[:9]] + [10 if digits[9] == "X" else int(digits[9])]
        return sum(weight * value for weight, value in zip(range(10, 0, -1), values)) % 11 == 0

    # ISBN-13: thirteen digits.
    if len(digits) == 13 and digits.isdigit():
        return sum((1 if index % 2 == 0 else 3) * int(char) for index, char in enumerate(digits)) % 10 == 0
    return False


def is_valid_url(url: str) -> bool:
    """An http(s) URL with a host name and no spaces."""
    parsed = urlparse(url)
    return parsed.scheme in ("http", "https") and "." in parsed.netloc and " " not in url


_IDENTIFIER_RULES = {
    "doi": (is_valid_doi, "a DOI of the form 10.<registrant>/<suffix>"),
    "isbn": (is_valid_isbn, "an ISBN-10 or ISBN-13 with a correct check digit"),
    "url": (is_valid_url, "an http(s) URL"),
}


