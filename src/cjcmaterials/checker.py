def _material_files(folders: str | Path | Iterable[str | Path] | None) -> list[Path]:
    """All material files of the given folders (the bundled library when None), sorted by name."""
    if folders is None:
        folder_list = [LIBRARY_DIR]
    elif isinstance(folders, (str, Path)):
        folder_list = [Path(folders)]
    else:
        folder_list = [Path(folder) for folder in folders]
    for folder in folder_list:
        if not folder.is_dir():
            raise FileNotFoundError(f"Material folder {folder} not found.")
    return sorted((path for folder in folder_list for path in folder.glob("*.yaml")),
                  key=lambda path: path.stem.lower())


def library_overview(folders: str | Path | Iterable[str | Path] | None = None) -> str:
    """The text of ``LIBRARY.md``: every material, description and source of the library.

    Generated from the YAML files, which stay the only source of truth;
    :func:`check_library` reports when the file differs from this text.
    """
    materials = [load_material_file(path) for path in _material_files(folders)]
    lines = [OVERVIEW_HEADER, "", "# Material library", "",
             "Every description with its model, valid range and sources, and whether each source has",
             "been checked against the original by a person (`no`, or who and when).", "",
             "| Material | Description | Model | Valid range [THz] | Sources |",
             "|----------|-------------|-------|-------------------|---------|"]

    # One table row per description, its sources by key.
    for material in materials:
        for description in material.descriptions:
            keys = ", ".join(f"`{source.key}`" for source in _all_sources(description))
            lines.append(f"| {material.name} | {description.label} | {description.model} | "
                         f"{_format_ranges(description.valid_range_thz)} | {keys} |")

    # Then every source per material, with where to find the values and its checked status.
    lines += ["", "## Sources", ""]
    for material in materials:
        lines += [f"### {material.name}", ""]
        for source in material.sources:
            lines.append(f"- `{source.key}` ({source.type} {source.identifier}): {source.citation}. "
                         f"Location: {source.location}. Valid: {_format_ranges(source.valid_range_thz)} THz. "
                         f"Checked: {source.checked}.")
        lines.append("")
    return "\n".join(lines)


def default_overview_path() -> Path | None:
    """``LIBRARY.md`` in the repository root of a source checkout; None for an installed package."""
    return _REPOSITORY_ROOT / "LIBRARY.md" if (_REPOSITORY_ROOT / "pyproject.toml").is_file() else None


def check_library(
    folders: str | Path | Iterable[str | Path] | None = None,
    *,
    overview_path: str | Path | None = None,
    online: bool = False,
    require_checked: bool = False,
    timeout: float = 15.0,
) -> LibraryCheck:
    """Check every material file of a library.

    Rules, grouped as in ``GROUPS``:

    - loading: every file can be read;
    - completeness: name = file name; unique labels; every description has
      sources and a valid range; every source has a type out of doi / isbn /
      url, an id, a citation, a location, a valid range and a ``checked``
      field of the form ``no`` or ``<who>, <YYYY-MM-DD>``; no unused sources;
    - identifiers: DOI, ISBN (check digit) and URL syntax;
    - valid ranges: 0 < min < max; a description's range lies inside each of
      its sources' ranges and inside its table (n and kappa);
    - physical sanity: known parameters have physical signs; each description
      evaluated over its own range gives a finite n and kappa >= 0, and a
      positive plasma frequency, mobility and scattering time, without and
      with carriers of each type;
    - overview: ``overview_path`` (``LIBRARY.md``) equals :func:`library_overview`;
    - online (only with ``online=True``): DOIs resolve and their title, first
      author and year match the citation; URLs respond.

    Sources with ``checked: no`` are listed separately; they fail the check
    only with ``require_checked=True``.

    Parameters
    ----------
    folders : path or list of paths, optional
        Folders with material files; default the bundled library.
    overview_path : path, optional
        The ``LIBRARY.md`` to compare. Default: the repository's own for the
        bundled library in a source checkout, none otherwise.
    online : bool, default False
        Also run the online checks (needs network access).
    require_checked : bool, default False
        Count unchecked sources as problems.
    timeout : float, default 15.0
        Seconds per online request.
    """
    problems: dict[str, list[str]] = {group: [] for group in GROUPS}

    # Load every file; a file that cannot be read is reported and skipped by the other rules.
    materials = []
    files = _material_files(folders)
    for path in files:
        try:
            material = load_material_file(path)
        except (OSError, ValueError) as error:
            problems["loading"].append(f"{path.name}: {error}")
            continue
        materials.append(material)
        problems["completeness"] += _check_completeness(material, path)
        problems["identifiers"] += _check_identifiers(material)
        problems["valid ranges"] += _check_ranges(material)
        problems["physical sanity"] += _check_physics(material)

    # The overview must match the files (only when all of them load, otherwise it cannot be generated).
    if overview_path is None and folders is None:
        overview_path = default_overview_path()
    if overview_path is not None and not problems["loading"]:
        overview_file = Path(overview_path)
        written = overview_file.read_text(encoding="utf-8").replace("\r\n", "\n") if overview_file.is_file() else None
        if written is None:
            problems["overview"].append(f"{overview_file} does not exist; create it with --write-overview.")
        elif written.rstrip("\n") != library_overview(folders).rstrip("\n"):
            problems["overview"].append(f"{overview_file} is out of date; regenerate it with --write-overview.")

    # Online checks last: they are slow and need the network.
    if online:
        problems["online"] += _check_online(materials, timeout)

    # Unchecked sources are a to-do list for a person, failing only on request.
    unchecked = tuple(f"{material.name}: {source.key} ({source.type} {source.identifier}) {source.citation}"
                      for material in materials for source in material.sources if source.checked == "no")
    found = {group: tuple(messages) for group, messages in problems.items() if messages}
    return LibraryCheck(
        problems=found,
        unchecked_sources=unchecked,
        materials=tuple(material.name for material in materials),
        passed=not found and not (require_checked and unchecked),
    )
